void vga_set_mode13h(void) {
    /* standard VGA register sequence for 320x200x256 */
    outb(0x3C2, 0x63);
    outb(0x3C4, 0x04); outb(0x3C5, 0x03);   /* sequential, 8 dots */
    outb(0x3C4, 0x02); outb(0x3C5, 0x0F);   /* all planes */
    outb(0x3D4, 0x11); outb(0x3D5, 0x06);   /* v-retrace disable */
    outb(0x3D4, 0x00); outb(0x3D5, 0x5F);   /* h-total */
    outb(0x3D4, 0x01); outb(0x3D5, 0x4F);   /* h-display */
    outb(0x3D4, 0x02); outb(0x3D5, 0x50);   /* h-blank start */
    outb(0x3D4, 0x03); outb(0x3D5, 0x82);   /* end */
    outb(0x3D4, 0x04); outb(0x3D5, 0x54);   /* h-retrace start */
    outb(0x3D4, 0x05); outb(0x3D5, 0x80);   /* end */
    outb(0x3D4, 0x06); outb(0x3D5, 0x0B);   /* v-total */
    outb(0x3D4, 0x07); outb(0x3D5, 0x3E);   /* overflow */
    outb(0x3D4, 0x08); outb(0x3D5, 0x00);   /* preset row */
    outb(0x3D4, 0x09); outb(0x3D5, 0x40);   /* cell height 8 */
    outb(0x3D4, 0x10); outb(0x3D5, 0xEA);   /* v-blank start */
    outb(0x3D4, 0x11); outb(0x3D5, 0x8C);   /* v-blank end */
    outb(0x3D4, 0x12); outb(0x3D5, 0xDF);   /* v-retrace start */
    outb(0x3D4, 0x13); outb(0x3D5, 0x28);   /* end */
    outb(0x3D4, 0x14); outb(0x3D5, 0x00);   /* line compare */
    outb(0x3CE, 0x05); outb(0x3CF, 0x40);   /* graphics mode 0 */
    outb(0x3CE, 0x06); outb(0x3CF, 0x05);   /* odd/even off */
    outb(0x3CE, 0x07); outb(0x3CF, 0x0F);   /* color don't care */
    outb(0x3C6, 0x14);                      /* misc */
    gfx_clear(0x00);
}

void gfx_putpixel(int x, int y, u8 color) {
    if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H) return;
    VGA_FB[y * GFX_W + x] = color;
}

void gfx_fillrect(int x0, int y0, int x1, int y1, u8 color) {
    for (int y = y0; y <= y1 && y < GFX_H; y++)
        for (int x = x0; x <= x1 && x < GFX_W; x++)
            VGA_FB[y * GFX_W + x] = color;
}

void gfx_drawchar(int x, int y, char c, u8 fg, u8 bg) {
    const u8 *glyph = font8x8[(u8)c & 0x7F];
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++)
            gfx_putpixel(x + col, y + row,
                         (glyph[row] & (0x80 >> col)) ? fg : bg);
    }
}

void gfx_drawstring(int x, int y, const char *s, u8 fg, u8 bg) {
    while (*s) {
        gfx_drawchar(x, y, *s++, fg, bg);
        x += 8;
    }
}

void gfx_clear(u8 color) {
    memset((void*)VGA_FB, color, GFX_W * GFX_H);
}
